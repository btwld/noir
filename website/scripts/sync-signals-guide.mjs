import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { format } from 'prettier';

const websiteRoot = fileURLToPath(new URL('../', import.meta.url));
const guideRoot = join(websiteRoot, '../packages/noir_signals/doc');
const source = await readFile(join(guideRoot, 'getting-started.md'), 'utf8');
const imageNames = new Set();
const body = source.replace(
  /\]\(\.\/images\/([a-z0-9-]+\.jpg)\)/g,
  (_, name) => {
    imageNames.add(name);
    return `](/demos/signals-task-list/${name})`;
  },
);
const target = join(websiteRoot, 'src/content/docs/signals-task-list.mdx');
const page = `---
title: Build a task list
description: Add hooks and Signals one step at a time, with complete Dart checkpoints and screenshots of the app.
---

{/* Generated by scripts/sync-signals-guide.mjs from packages/noir_signals/doc/getting-started.md. */}

${body}`;

await writeFile(target, await format(page, { filepath: target }));
const imageRoot = join(websiteRoot, 'public/demos/signals-task-list');
await mkdir(imageRoot, { recursive: true });
for (const name of imageNames) {
  const image = await readFile(join(guideRoot, 'images', name));
  await writeFile(join(imageRoot, name), image);
}

console.log(`Synced Signals guide and ${imageNames.size} screenshots.`);
