import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { codeToHtml } from 'shiki';

const websiteRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = join(websiteRoot, 'src/lib/counter-example.ts');
const outputPath = join(websiteRoot, 'src/lib/counter-highlight.ts');
const sourceFile = readFileSync(sourcePath, 'utf8');

function readExportedTemplate(name) {
  const match = sourceFile.match(
    new RegExp(`export const ${name} = \`([\\s\\S]*?)\`;`),
  );
  if (!match) {
    throw new Error(`Could not find ${name} in ${sourcePath}`);
  }
  return match[1];
}

const counterStateSource = readExportedTemplate('counterStateSource');
const counterAppSource = readExportedTemplate('counterAppSource');
if (!counterAppSource.includes(counterStateSource)) {
  throw new Error(
    'counterStateSource must remain an excerpt of counterAppSource',
  );
}

const gettingStarted = readFileSync(
  join(websiteRoot, 'src/content/docs/getting-started.mdx'),
  'utf8',
);
const dartFence = gettingStarted.match(/```dart\n([\s\S]*?)\n```/);
if (!dartFence || dartFence[1] !== counterAppSource) {
  throw new Error(
    'getting-started.mdx dart fence must equal counterAppSource exactly',
  );
}
if (!gettingStarted.includes("from '../../lib/counter-example'")) {
  throw new Error(
    'getting-started.mdx must import the shared counter frame constants',
  );
}

const html = await codeToHtml(counterStateSource.trimEnd(), {
  defaultColor: false,
  lang: 'dart',
  tabindex: false,
  themes: {
    dark: 'github-dark',
    light: 'github-light',
  },
});

writeFileSync(
  outputPath,
  `// Generated by scripts/highlight-homepage.mjs. Do not edit by hand.\nexport const counterStateHtml = ${JSON.stringify(html)};\n`,
);

console.log(`Wrote ${outputPath}`);
