/// Parses every `static const String` declared by [Icons] from source, so the
/// guard covers constants a future edit adds without touching this test.
Map<String, String> _declaredIcons() {
  final source = File('lib/src/widgets/icons.dart').readAsStringSync();
  final pattern = RegExp(
    r"static const String (\w+) = '(.+?)';",
    multiLine: true,
  );
  final declared = <String, String>{
    for (final match in pattern.allMatches(source))
      match.group(1)!: match.group(2)!,
  };
  if (declared.isEmpty) {
    throw StateError('No Icons constants parsed; the declaration shape moved.');
  }
  return declared;
}

bool _contains(List<int> ranges, int codePoint) {
  var low = 0;
  var high = ranges.length ~/ 2 - 1;
  while (low <= high) {
    final middle = (low + high) >> 1;
    if (codePoint < ranges[middle * 2]) {
      high = middle - 1;
    } else if (codePoint > ranges[middle * 2 + 1]) {
      low = middle + 1;
    } else {
      return true;
    }
  }
  return false;
}

