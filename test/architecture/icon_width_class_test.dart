    expect(
      declared.keys.toSet(),
      equals({...narrowGroup, ...ambiguousGroup}),
      reason:
          'A new Icons constant must be added to narrowGroup or '
          'ambiguousGroup so its width class is checked.',
    );
    expect(narrowGroup.intersection(ambiguousGroup), isEmpty);
  });

  test('every Icons constant occupies exactly one cell', () {
    for (final entry in declared.entries) {
      expect(
        entry.value.characters.length,
        1,
        reason: 'Icons.${entry.key} must be a single grapheme cluster.',
      );
      expect(
        terminalCellWidth(entry.value),
