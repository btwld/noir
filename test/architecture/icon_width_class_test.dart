        reason: "Icons.${entry.key} must be one cell in Noir's width model.",
      );
    }
  });

  test('no Icons constant carries the Unicode Emoji property', () {
    for (final entry in declared.entries) {
      final codePoint = entry.value.runes.single;
      expect(
        codePoint,
        lessThanOrEqualTo(0xFFFF),
        reason: 'Icons.${entry.key} must stay in the BMP.',
